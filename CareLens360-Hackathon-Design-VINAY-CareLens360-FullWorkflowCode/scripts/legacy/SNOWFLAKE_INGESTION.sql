INSERT INTO PATIENT_360_RAG.RAW.DOCUMENT_MANIFEST
    (FILE_NAME,FILE_TYPE, FILE_PATH, FILE_URL, DOCUMENT_TYPE)
SELECT
    split(RELATIVE_PATH, '/')[1] as FILE_NAME, -- FILE NAME 
    split(RELATIVE_PATH, '/')[0] as FILE_TYPE, -- STRUCTURED / UNSTRUCTURED
    RELATIVE_PATH,
    FILE_URL,
    CASE WHEN split_part(RELATIVE_PATH, '.',-1) = 'csv' THEN 'CSV'
    WHEN split_part(RELATIVE_PATH, '.',-1) = 'pdf' THEN 'PDF'
    WHEN split_part(RELATIVE_PATH, '.',-1) = 'jpeg' THEN 'JPEG'
    WHEN split_part(RELATIVE_PATH, '.',-1) = 'json' THEN 'JSON'
    ELSE NULL
    END AS DOCUMENT_TYPE
FROM DIRECTORY(
    @PATIENT_360_RAG.RAW.DOCUMENT_STAGE
);


