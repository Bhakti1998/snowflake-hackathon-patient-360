---- PARSE THE UNSTRUCTURED DOCUMENTS USING AI PARSED DOCUMENT Function
CREATE OR REPLACE TABLE PATIENT_360_RAG.RAW.PARSED_DOCUMENTS AS
SELECT
    m.DOCUMENT_ID,
    m.FILE_PATH,
    m.DOCUMENT_TYPE,
    AI_PARSE_DOCUMENT(
        TO_FILE('@PATIENT_360_RAG.RAW.DOCUMENT_STAGE', m.FILE_PATH),
        {'mode': 'LAYOUT', 'page_split': true}
    ) AS PARSED_JSON
FROM PATIENT_360_RAG.RAW.DOCUMENT_MANIFEST m
WHERE m.FILE_TYPE = 'UNSTRUCTURED' AND m.DOCUMENT_TYPE IN ('PDF')
AND NOT EXISTS(SELECT 1 FROM PATIENT_360_RAG.RAW.PARSED_DOCUMENTS p WHERE p.DOCUMENT_ID = m.DOCUMENT_ID);

