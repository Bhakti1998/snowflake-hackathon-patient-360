insert into PATIENT_360_RAG.RAW.DOCUMENT_CHUNKS
SELECT
    p.DOCUMENT_ID,
    REGEXP_SUBSTR(
    p.PARSED_JSON:content::VARCHAR,
    'Patient:\\s*(.*?)\\s+MRN:',
    1,
    1,
    'e',
    1 ) AS PATIENT_NAME,

    REGEXP_SUBSTR(
        p.PARSED_JSON:content::VARCHAR,
        'MRN:\\s*([^\\s]+)',
        1, 1, 'e', 1
    ) AS MRN,

    REGEXP_SUBSTR(
        p.PARSED_JSON:content::VARCHAR,
        'Encounter:\\s*([^\\s]+)',
        1, 1, 'e', 1
    ) AS ENCOUNTER_ID,
    p.FILE_PATH,
    page.index + 1 AS PAGE_NUMBER,
    chunk.index AS CHUNK_INDEX,
    chunk.value::VARCHAR AS CHUNK_TEXT,
    PARSED_JSON as METADATA,
    CURRENT_TIMESTAMP() as CREATED_AT
FROM PATIENT_360_RAG.RAW.PARSED_DOCUMENTS p,
LATERAL FLATTEN(
    INPUT => p.PARSED_JSON
) page
,
LATERAL FLATTEN(
    INPUT => SNOWFLAKE.CORTEX.SPLIT_TEXT_RECURSIVE_CHARACTER(
        p.PARSED_JSON:content::VARCHAR,
        'markdown',
        800,
        100
    )
) chunk
WHERE p.PARSED_JSON IS NOT NULL and p.document_type='JPEG';



