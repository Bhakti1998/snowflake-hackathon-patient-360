--- PROCEDURE TO UPLOAD ALL CSV FILES INTO SNOWFLAKE TABLES
--- THIS DOES NOT NEED ANY PARSING OR CHUNKING AS IT IS ALREADY STRUCTURED AND WILL BE PASSED TO CORTEX SEARCH SERVICE
CREATE OR REPLACE PROCEDURE PATIENT_360_RAG.RAW.LOAD_ALL_CSV_FILES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    v_file_path   VARCHAR;
    v_file_name   VARCHAR;
    v_table_name  VARCHAR;
    v_sql         VARCHAR;
    updt_sql         VARCHAR;
    v_count       NUMBER DEFAULT 0;

    c1 CURSOR FOR
        SELECT FILE_PATH
        FROM PATIENT_360_RAG.RAW.DOCUMENT_MANIFEST
        WHERE DOCUMENT_TYPE = 'CSV'
          AND FILE_PATH IS NOT NULL;

BEGIN

    FOR rec IN c1 DO

        v_file_path := rec.FILE_PATH;

        -- Get filename from path
        v_file_name := REGEXP_SUBSTR(
            v_file_path,
            '[^/]+$'
        );

        -- Remove .csv and convert to uppercase
        v_table_name := UPPER(
            REGEXP_REPLACE(
                v_file_name,
                '\\.csv$',
                ''
            )
        );

        -- Create table using inferred schema
        v_sql :=
            'CREATE OR REPLACE TABLE PATIENT_360_RAG.RAW.' ||
            v_table_name ||
            ' USING TEMPLATE (' ||
            'SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) ' ||
            'FROM TABLE(INFER_SCHEMA(' ||
            'LOCATION => ''@PATIENT_360_RAG.RAW.DOCUMENT_STAGE/' ||
            v_file_path ||
            ''',' ||
            'FILE_FORMAT => ''PATIENT_360_RAG.RAW.MYCSVFORMAT''' ||
            ')))';

        EXECUTE IMMEDIATE v_sql;

        -- Load CSV
        v_sql :=
            'COPY INTO PATIENT_360_RAG.RAW.' ||
            v_table_name ||
            ' FROM @PATIENT_360_RAG.RAW.DOCUMENT_STAGE/' ||
            v_file_path ||
            ' FILE_FORMAT = (' ||
            'FORMAT_NAME = ''PATIENT_360_RAG.RAW.MYCSVFORMAT''' ||
            ') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE';

        EXECUTE IMMEDIATE v_sql;

        updt_sql := 'UPDATE PATIENT_360_RAG.RAW.DOCUMENT_MANIFEST
             SET INGESTION_STATUS = ''LOADED''
             WHERE FILE_PATH = ''' || v_file_path || '''';

        EXECUTE IMMEDIATE updt_sql;
        
        v_count := v_count + 1;

    END FOR;

    RETURN 'Successfully processed ' || v_count || ' CSV files';

END;
$$;


